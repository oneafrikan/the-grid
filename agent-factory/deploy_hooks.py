#!/usr/bin/env python3
"""deploy_hooks.py — emit the grid's Claude Code guard hooks into one project's settings.

The hooks themselves live once, in the-grid's hooks/ dir, behind one launcher
(hooks/run.sh) and one catalogue (hooks/catalogue.json). A project never carries a
copy of a script: this writes only a small settings entry per hook that calls the
launcher, so nothing can drift. Which hooks a project gets is a profile:

    off       nothing (and any entry this tool wrote earlier is removed)
    minimal   pre-bash-no-bypass
    standard  minimal + pre-bash-secret-scan
    strict    same as standard for now (the name is reserved for a stricter guard)

Usage:
    deploy_hooks.py <project-dir> [--profile P] [--target local|shared]
    deploy_hooks.py <project-dir> --check      # drift report; writes nothing; exit 1 on drift
    deploy_hooks.py <project-dir> --dry-run    # show what would change; write nothing
    deploy_hooks.py --list                     # every hook: scope, min profile, cost, model use
    deploy_hooks.py --user --hooks <id,id|""> [--check] [--dry-run]   # machine-level (see below)

Project facts come from an optional <project-dir>/.grid/project.yaml (the same file
deploy.py reads; this tool reads only its `hooks:` key):
    hooks:
      profile: standard    # off | minimal | standard | strict   (absent = off)
      target: local        # local (default) -> .claude/settings.local.json (machine-local)
                           # shared          -> .claude/settings.json (committed)
Resolution: --profile / --target flag, then the file, then off / local. Any other key
under `hooks:` is an error. User-scope catalogue hooks are never written to a project.

Opt-in hooks (catalogue entries with "opt_in": "learning" instead of "min_profile") are
not part of any profile. They are emitted exactly when the project.yaml top-level key
`learning` is on (the last top-level `learning:` line reads `on` or `true`, any case, quotes
and a trailing comment allowed; bare `yes` is off; one shared parser, scripts/instincts/lib.py),
under every profile including `off`, and removed again when the flag goes off (see
docs/instincts.md). `hooks:` still has no per-hook list. Applying (not --check/--dry-run) also
creates or removes a machine-local marker under the state dir that capture requires as well,
and prints a one-line data-use notice when the instincts hooks are emitted.

What lands in <project-dir>/.claude/:
    settings.local.json   (or settings.json with target: shared) gains one handler per hook:
      bash "${GRID_DIR:-$HOME/.the-grid}/hooks/run.sh" <id> # GENERATED by the-grid deploy_hooks.py
    The command carries no absolute path, so a committed file works on any machine that has
    the-grid at its documented location (or GRID_DIR set).

User mode (--user, run by scripts/wire.sh; user-scope hooks only, e.g. auto-handoff):
    --hooks names the user-scope ids that SHOULD be present in
    ${CLAUDE_CONFIG_DIR:-$HOME/.claude}/settings.json; every other entry this tool wrote
    there is removed, and `--hooks ""` removes them all. Unknown or project-scope ids are
    rejected (exit 2) before anything is read or written. The command uses the ABSOLUTE
    path of the grid (a machine-level file is never committed, so no portable form is
    needed):
      bash "<abs GRID_DIR>/hooks/run.sh" <id> # GENERATED by the-grid deploy_hooks.py
    Needs only the stdlib, so it runs under any python3 (no venv). --check exits 1 on
    drift and writes nothing; --dry-run prints the plan and writes nothing.

Safety (project and user mode):
  - ownership: a handler is ours only if its command matches OWNED_RE (the launcher path,
    an id, and the trailing GENERATED comment). Anything else is hand-written and is never
    edited, reordered or removed. No lock file: every run sweeps both settings files.
  - both settings files are swept; entries are only ever ADDED to the target file, so
    changing `target` moves entries instead of duplicating them
  - a symlinked .claude or settings file, invalid JSON, or a non-object file aborts the run
    before anything is written (a user's settings are never silently discarded)
  - writes are atomic (temp file + rename); a settings file is never created just to hold
    nothing; re-running with unchanged inputs is a byte-for-byte no-op
  - the merge is one function, merge_owned(), shared by project mode and --user mode
  - user mode refuses a symlinked config dir or settings.json (replacing the file would
    break a dotfiles link) just as project mode refuses a symlinked .claude

Stdlib only at import time. PyYAML (the agent-factory venv) is imported lazily, and only
when a project has a .grid/project.yaml to read.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import re
import sys
import tempfile
from pathlib import Path

# Profiles in ascending order; a profile includes every hook whose min_profile ranks at or
# below it. `strict` is accepted now and adds nothing beyond `standard` (catalogue-driven).
PROFILES = ("off", "minimal", "standard", "strict")
TARGETS = ("local", "shared")
# Where each target writes, relative to the project dir.
SETTINGS_REL = {"local": Path(".claude/settings.local.json"), "shared": Path(".claude/settings.json")}
CONTEXT_REL = Path(".grid/project.yaml")
OPT_INS = ("learning",)  # the only opt_in value a catalogue entry may carry
ALLOWED_KEYS = ("profile", "target")  # the only keys allowed under `hooks:` in project.yaml

# Portable launcher path: no absolute path, so a committed settings file works anywhere.
# Written literally (the shell expands it when the hook runs, not this script).
LAUNCHER = '"${GRID_DIR:-$HOME/.the-grid}/hooks/run.sh"'
GENERATED = "# GENERATED by the-grid deploy_hooks.py"
# Ownership test (design.md): the whole command must have this exact shape. JSON cannot
# carry a comment and unknown handler keys may be rejected, so the marker lives in the
# command as a trailing shell comment. Group 1 is the hook id.
OWNED_RE = re.compile(r'^bash "[^"]*/hooks/run\.sh" ([a-z0-9-]+) # GENERATED by the-grid deploy_hooks\.py$')
ID_RE = re.compile(r"^[a-z0-9-]+$")

REPO_ROOT = Path(__file__).resolve().parent.parent


def die(msg: str) -> "None":
    print(f"deploy_hooks: {msg}", file=sys.stderr)
    sys.exit(1)


class SettingsError(ValueError):
    """A settings structure the merge cannot safely touch (not an object, hooks not a list...)."""


# ── catalogue ─────────────────────────────────────────────────────────────────
def grid_dir() -> Path:
    """The grid whose catalogue is read: $GRID_DIR, else this script's own repo."""
    return Path(os.environ.get("GRID_DIR") or REPO_ROOT)


def load_catalogue(grid: Path) -> list[dict]:
    """The validated hook entries of <grid>/hooks/catalogue.json.

    The id ends up inside a shell command written to a settings file, so it is held to
    the same [a-z0-9-]+ shape the launcher and OWNED_RE accept; everything else is checked
    only as far as this tool relies on it."""
    path = grid / "hooks" / "catalogue.json"
    if not path.is_file():
        die(f"hook catalogue not found: {path} (set GRID_DIR to a the-grid checkout)")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        die(f"{path}: invalid JSON ({exc})")
    if not isinstance(data, dict) or data.get("version") != 1 or not isinstance(data.get("hooks"), list):
        die(f"{path}: expected an object with version 1 and a 'hooks' list")
    seen: set[str] = set()
    for h in data["hooks"]:
        hid = h.get("id") if isinstance(h, dict) else None
        if not (isinstance(hid, str) and ID_RE.fullmatch(hid)):
            die(f"{path}: hook id {hid!r} must match [a-z0-9-]+")
        if hid in seen:
            die(f"{path}: duplicate hook id '{hid}'")
        seen.add(hid)
        if h.get("scope") not in ("project", "user"):
            die(f"{path}: hook '{hid}': scope must be 'project' or 'user'")
        if not (isinstance(h.get("event"), str) and h["event"]):
            die(f"{path}: hook '{hid}': 'event' must be a non-empty string")
        if not (isinstance(h.get("timeout"), int) and not isinstance(h["timeout"], bool) and h["timeout"] > 0):
            die(f"{path}: hook '{hid}': 'timeout' must be a positive integer")
        if "matcher" in h and not isinstance(h["matcher"], str):
            die(f"{path}: hook '{hid}': 'matcher' must be a string when present")
        # on_failure: block makes Claude Code itself block when the hook fails or times
        # out (a timed-out hook is otherwise non-blocking). Needs Claude Code 2.1.295+.
        if "on_failure" in h and h["on_failure"] != "block":
            die(f"{path}: hook '{hid}': 'on_failure' must be 'block' when present")
        if "opt_in" in h and h["scope"] != "project":
            die(f"{path}: hook '{hid}': opt_in applies to project hooks only")
        if h["scope"] == "project":
            # Exactly one way into a project: a profile floor, or an opt-in flag.
            if "opt_in" in h and "min_profile" in h:
                die(f"{path}: hook '{hid}': give min_profile or opt_in, not both")
            if "opt_in" in h:
                if h["opt_in"] not in OPT_INS:
                    die(f"{path}: hook '{hid}': opt_in must be one of {', '.join(OPT_INS)}")
            elif h.get("min_profile") not in PROFILES[1:]:
                die(f"{path}: hook '{hid}': project hooks need min_profile in {', '.join(PROFILES[1:])} (or opt_in)")
    return data["hooks"]


def user_settings_path() -> Path:
    """The user-level settings file: ${CLAUDE_CONFIG_DIR:-$HOME/.claude}/settings.json."""
    base = os.environ.get("CLAUDE_CONFIG_DIR") or str(Path.home() / ".claude")
    return Path(base).expanduser() / "settings.json"


def user_desired(hooks: list[dict], ids: list[str], grid: Path) -> list[tuple]:
    """(event, matcher|None, command, timeout, on_failure|None) for each requested user-scope id.

    Exits 2, before anything is read or written, on an id that is not in the catalogue
    or is not user-scope (a project hook belongs to a project profile, never to the
    machine-wide file). The grid path is written ABSOLUTE into the command, so it is
    held to characters that cannot break out of the double quotes or fail OWNED_RE."""
    by_id = {h["id"]: h for h in hooks}
    out = []
    for hid in dict.fromkeys(ids):  # de-duplicated, order kept
        h = by_id.get(hid)
        if h is None:
            print(f"deploy_hooks: unknown hook id {hid!r} (user-scope ids: "
                  f"{', '.join(x['id'] for x in hooks if x['scope'] == 'user') or 'none'})", file=sys.stderr)
            sys.exit(2)
        if h["scope"] != "user":
            print(f"deploy_hooks: {hid!r} is a project-scope hook; --user takes user-scope ids only "
                  f"(project hooks come from a project profile)", file=sys.stderr)
            sys.exit(2)
        grid_s = str(grid)
        if re.search(r'["$`\\\n]', grid_s):
            die(f"grid path {grid_s!r} contains a character that cannot be written safely into a hook command")
        out.append((h["event"], h.get("matcher"), f'bash "{grid_s}/hooks/run.sh" {hid} {GENERATED}', h["timeout"], h.get("on_failure")))
    return out


def print_list(hooks: list[dict]) -> None:
    """--list: one row per hook, so the cost of every profile choice is visible."""
    width = max([len(h["id"]) for h in hooks] + [2])
    print(f"{'id':<{width}}  {'scope':<7}  {'min_profile':<15}  {'model_cost':<10}  cost")
    for h in hooks:
        # min_profile only means something for project hooks; user hooks have no profile.
        minp = h.get("min_profile", "-") if h["scope"] == "project" else "-"
        if h["scope"] == "project" and "opt_in" in h:
            minp = f"opt-in:{h['opt_in']}"  # not in any profile; a project.yaml flag turns it on
        model = "yes" if h.get("model_cost") else "no"
        print(f"{h['id']:<{width}}  {h['scope']:<7}  {minp:<15}  {model:<10}  {h.get('cost', '')}")


# ── project.yaml (the `hooks:` key) ───────────────────────────────────────────
def load_hooks_config(project: Path) -> dict:
    """The validated `hooks:` mapping of <project>/.grid/project.yaml ({} when absent).

    Strict on purpose: an unknown key or value is an error, never ignored, so a typo
    cannot silently leave a project unguarded."""
    path = project / CONTEXT_REL
    if path.is_symlink():
        die(f"refusing: {path} is a symlink")
    if not path.is_file():
        return {}
    try:
        import yaml  # lazy: only project mode with a project.yaml needs it
    except ImportError:
        die("PyYAML is required to read .grid/project.yaml; run with agent-factory/.venv/bin/python")
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as exc:
        die(f"{path}: invalid YAML: {str(exc).splitlines()[0]}")
    if not isinstance(data, dict):
        die(f"{path}: must be a mapping")
    hooks = data.get("hooks")
    if hooks is None:
        return {}
    if not isinstance(hooks, dict):
        die(f"{path}: 'hooks' must be a mapping (allowed keys: {', '.join(ALLOWED_KEYS)})")
    unknown = sorted(str(k) for k in set(hooks) - set(ALLOWED_KEYS))
    if unknown:
        die(f"{path}: unknown key(s) under hooks: {unknown} (allowed: {', '.join(ALLOWED_KEYS)})")
    cfg = dict(hooks)
    # YAML 1.1 reads a bare `off` as boolean false; the schema's value is the word "off".
    if cfg.get("profile") is False:
        cfg["profile"] = "off"
    if "profile" in cfg and cfg["profile"] not in PROFILES:
        die(f"{path}: unknown hooks.profile {cfg['profile']!r} (allowed: {', '.join(PROFILES)})")
    if "target" in cfg and cfg["target"] not in TARGETS:
        die(f"{path}: unknown hooks.target {cfg['target']!r} (allowed: {', '.join(TARGETS)})")
    return cfg


def _instincts_lib():
    """scripts/instincts/lib.py of THIS repo (not $GRID_DIR: a fixture grid has none).

    It is stdlib-only and holds the one `learning` parser and the opt-in marker helpers,
    so the emitter and the capture hooks cannot disagree."""
    sys.dont_write_bytecode = True  # importing must not drop a __pycache__ into the repo
    d = str(REPO_ROOT / "scripts" / "instincts")
    if d not in sys.path:
        sys.path.insert(0, d)
    import lib  # noqa: PLC0415
    return lib


def load_learning_flag(project: Path) -> bool:
    """True when <project>/.grid/project.yaml has the top-level `learning` key switched on.

    Parsed by lib.read_learning_flag, the same function capture uses: last `learning:` line
    wins, quotes and a trailing comment are allowed, and only `on`/`true` (any case) are on;
    bare `yes`, `1` and unknown values are off. No file, a symlink or no key is off. Not
    strict like `hooks:`: the value is a switch, and an unrecognised value just leaves it off."""
    path = project / CONTEXT_REL
    if path.is_symlink() or not path.is_file():
        return False
    try:
        return _instincts_lib().read_learning_flag(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError):
        return False


NOTICE = ("instincts: prompts and shell commands are recorded locally (lines holding secrets or "
          "personal data are dropped) and a scrubbed digest is sent to a model weekly; "
          "set learning: off and re-run this tool to stop")


def sync_learning_marker(project: Path, emitting: bool) -> None:
    """Create (instincts hooks emitted) or remove (not emitted) the machine-local opt-in marker.

    Capture needs the repo flag AND this marker (design D44), so a cloned repo cannot turn
    capture on by itself. Needs a git remote (the marker is named by the project id). A failure
    here is a warning: it must not undo the settings files already written."""
    try:
        lib = _instincts_lib()
        root = lib._git(str(project), "rev-parse", "--show-toplevel") or str(project)
        pid = lib.git_project_id(root)
        if not pid:
            if emitting:
                print("deploy_hooks: warning: no git remote, so instincts capture stays off "
                      "(the project id is derived from the remote)", file=sys.stderr)
            return
        if emitting:
            lib.write_marker(pid, root)
        else:
            lib.remove_marker(pid, root)
    except (OSError, ValueError) as exc:
        print(f"deploy_hooks: warning: could not update the instincts marker: {exc}", file=sys.stderr)


def desired_for(hooks: list[dict], profile: str, learning: bool = False) -> list[tuple]:
    """(event, matcher|None, command, timeout, on_failure|None) for every project-scope hook the profile
    includes, plus every `opt_in: learning` hook when the learning flag is on (whatever the
    profile). User-scope hooks are filtered out here and can never reach a project file."""
    rank = PROFILES.index(profile)
    out = []
    for h in hooks:
        if h["scope"] != "project":
            continue
        if "opt_in" in h:
            # Never selected by a profile; only by its flag.
            if not (h["opt_in"] == "learning" and learning):
                continue
        elif PROFILES.index(h["min_profile"]) > rank:
            continue
        command = f"bash {LAUNCHER} {h['id']} {GENERATED}"
        out.append((h["event"], h.get("matcher"), command, h["timeout"], h.get("on_failure")))
    return out


# ── the merge (shared by project mode and --user mode) ────────────────────────
def is_owned(handler) -> bool:
    """True for a handler this tool wrote (command matches OWNED_RE); never for a
    hand-written one."""
    return isinstance(handler, dict) and isinstance(handler.get("command"), str) \
        and OWNED_RE.match(handler["command"]) is not None


def iter_owned(settings: dict):
    """Yield (event, matcher|None, handler) for every owned handler in a settings dict.
    Tolerant of odd shapes: anything that is not the expected container is skipped."""
    hooks = settings.get("hooks")
    if not isinstance(hooks, dict):
        return
    for event, entries in hooks.items():
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if isinstance(entry, dict) and isinstance(entry.get("hooks"), list):
                for h in entry["hooks"]:
                    if is_owned(h):
                        yield event, entry.get("matcher"), h


def sweep_scope(catalogue: list[dict], scope: str):
    """Predicate "may this mode sweep (remove) an owned handler with this id?".

    OWNED_RE ownership is agent-wide, so with the user file and a project's settings file
    being the same path (project dir = a home, or CLAUDE_CONFIG_DIR at a project's .claude)
    each mode would otherwise sweep the OTHER mode's handlers (R02.qa.F3). A mode sweeps
    its own scope's ids plus ids the catalogue no longer knows (a retired hook must still
    go away); it never touches an id the catalogue assigns to the other scope."""
    other = {h["id"] for h in catalogue if h["scope"] != scope}
    return lambda hid: hid not in other


def merge_owned(settings: dict, desired: list[tuple], sweeps=None) -> dict:
    """Return a copy of `settings` whose owned hook handlers are exactly `desired`.

    desired: [(event, matcher|None, command, timeout, on_failure|None)]. Semantics are those of the
    jq `merge_hook` this replaces (find the entry with the same matcher, then append
    the handler unless its command is already there; matcher-less events like
    SessionEnd use the entry with no matcher), plus:
      - owned handlers that are no longer desired (including one whose command differs
        from the desired one, e.g. another path) are removed
      - only the containers that removal emptied are pruned (entry, event, "hooks");
        an empty container the user left behind is not ours to tidy
      - running it twice is a no-op, and key order of everything untouched is kept
    Hand-written handlers are never edited, reordered or removed. `sweeps` (see
    sweep_scope) limits which owned ids this call may remove; None means all of them.
    Raises SettingsError when something must be added into a container of the wrong type."""
    out = copy.deepcopy(settings)
    wanted = {(event, matcher, command): (timeout, on_failure)
              for event, matcher, command, timeout, on_failure in desired}

    # -- 1. sweep: drop owned handlers that are not wanted (or are duplicates) -------
    hooks = out.get("hooks")
    if isinstance(hooks, dict):
        seen: set[tuple] = set()
        hooks_emptied = False
        for event in list(hooks):
            entries = hooks[event]
            if not isinstance(entries, list):
                continue
            event_emptied = False
            for entry in list(entries):
                if not (isinstance(entry, dict) and isinstance(entry.get("hooks"), list)):
                    continue
                matcher = entry.get("matcher")
                kept, removed = [], False
                for h in entry["hooks"]:
                    if not is_owned(h) or (sweeps is not None and not sweeps(hook_id(h["command"]))):
                        kept.append(h)  # hand-written, or the other scope's: untouched, in place
                        continue
                    key = (event, matcher, h["command"])
                    if key in wanted and key not in seen:
                        seen.add(key)
                        if h.get("timeout") != wanted[key][0]:
                            h["timeout"] = wanted[key][0]  # catalogue timeout changed
                        if h.get("onFailure") != wanted[key][1]:
                            # catalogue on_failure changed: add, change or drop the field
                            if wanted[key][1] is None:
                                h.pop("onFailure", None)
                            else:
                                h["onFailure"] = wanted[key][1]
                        kept.append(h)
                    else:
                        removed = True
                if removed:
                    entry["hooks"][:] = kept
                    if not kept:  # removal emptied this entry: prune it (by identity)
                        entries[:] = [e for e in entries if e is not entry]
                        event_emptied = not entries
            if event_emptied:
                del hooks[event]
                hooks_emptied = not hooks
        if hooks_emptied:
            del out["hooks"]

    # -- 2. add: each desired handler into the entry with the same matcher ----------
    # The sweep keeps an owned handler wherever it already sits. Without this check the
    # add step looked only at the FIRST entry with the matcher, so a generated handler in
    # a later entry was kept by the sweep and appended again (two SessionEnd runs, two
    # model calls, until later runs happened to converge). "Present anywhere under the
    # same event and matcher" also never moves a handler into a user's own entry.
    present = {(event, matcher, h["command"]) for event, matcher, h in iter_owned(out)}
    for event, matcher, command, timeout, on_failure in desired:
        if (event, matcher, command) in present:
            continue
        if "hooks" in out and not isinstance(out["hooks"], dict):
            raise SettingsError("'hooks' is not an object")
        hooks = out.setdefault("hooks", {})
        entries = hooks.setdefault(event, [])
        if not isinstance(entries, list):
            raise SettingsError(f"hooks.{event} is not a list")
        handler = {"type": "command", "timeout": timeout, "command": command}
        if on_failure is not None:
            handler["onFailure"] = on_failure
        target = next((e for e in entries
                       if isinstance(e, dict) and isinstance(e.get("hooks"), list)
                       and e.get("matcher") == matcher), None)
        if target is None:
            entries.append({"matcher": matcher, "hooks": [handler]} if matcher is not None
                           else {"hooks": [handler]})
        elif not any(isinstance(h, dict) and h.get("command") == command for h in target["hooks"]):
            target["hooks"].append(handler)
    return out


# ── settings files ────────────────────────────────────────────────────────────
def check_no_symlinks(project: Path) -> None:
    """Refuse to read or write through a symlinked .claude, .grid or settings file (a
    link there would redirect the write somewhere outside the project)."""
    for rel in [Path(".claude"), Path(".grid")] + list(SETTINGS_REL.values()):
        if (project / rel).is_symlink():
            die(f"refusing: {project / rel} is a symlink")
    if (project / ".claude").exists() and not (project / ".claude").is_dir():
        die(f"{project / '.claude'} exists and is not a directory")


def check_user_no_symlinks(settings: Path) -> None:
    """User-mode twin of check_no_symlinks: refuse a symlinked config dir or settings
    file. Replacing a symlinked settings.json (atomic rename) would swap the link for a
    plain file and silently break a dotfiles setup; a symlinked dir could redirect the
    write. The operator resolves it by hand; wire.sh reports it as a warning."""
    for p in (settings.parent, settings):
        if p.is_symlink():
            die(f"refusing: {p} is a symlink")
    if settings.parent.exists() and not settings.parent.is_dir():
        die(f"{settings.parent} exists and is not a directory")


def read_settings(path: Path) -> tuple[dict, str | None]:
    """(parsed settings, raw text) of a settings file; ({}, None) when it is absent.
    Dies, before anything has been written, on anything the rewrite could corrupt or
    cannot write: a non-regular path (directory, FIFO), an empty file, invalid JSON, a
    non-object, duplicate keys or non-finite numbers (the rewrite would drop or re-emit
    them), and any I/O or encoding failure (a one-line error, never a traceback)."""
    if not os.path.lexists(path):
        return {}, None
    if not path.is_file():  # a directory or FIFO; symlinks were refused by the callers
        die(f"{path}: not a regular file; nothing was written")
    try:
        text = path.read_text(encoding="utf-8")
        if not text.strip():
            # Unverified whether Claude Code accepts an empty file (OPERATOR-TASKS), so keep
            # refusing it rather than guess; the message says how to get unblocked.
            die(f"{path}: is empty; delete it or write {{}} to it; nothing was written")
        data = json.loads(text, object_pairs_hook=_no_duplicate_keys,
                          parse_constant=_reject_constant, parse_float=_finite_float)
    except (ValueError, OSError, RecursionError) as exc:  # JSONDecodeError/UnicodeError are ValueErrors
        die(f"{path}: not valid JSON or not readable ({exc}); fix or remove it, nothing was written")
    if not isinstance(data, dict):
        die(f"{path}: must be a JSON object, nothing was written")
    return data, text


def _no_duplicate_keys(pairs):
    """json object_pairs_hook: json.loads keeps the last of two equal keys, so a rewrite
    would silently drop one. Refuse instead."""
    obj = {}
    for key, value in pairs:
        if key in obj:
            raise ValueError(f"duplicate key {key!r}")
        obj[key] = value
    return obj


def _reject_constant(name):
    """json parse_constant: NaN, Infinity and -Infinity are not JSON; Python accepts them
    and would re-emit them."""
    raise ValueError(f"non-finite number {name}")


def _finite_float(text):
    """json parse_float: 1e999 parses to infinity, which a rewrite would re-emit."""
    value = float(text)
    if value in (float("inf"), float("-inf")):
        raise ValueError(f"non-finite number {text}")
    return value


def render(settings: dict) -> str:
    """The bytes a settings file gets: 2-space indent, key order kept, trailing newline."""
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n"


def atomic_write(path: Path, text: str) -> None:
    """Temp file in the same directory, then rename; keeps an existing file's mode."""
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = (path.stat().st_mode & 0o777) if path.exists() else 0o644
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".grid-deploy-hooks-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(tmp, mode)  # mkstemp creates 0600
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def write_files(items: list[tuple[Path, str]]) -> None:
    """Write every (path, text) atomically, after checking ALL of them up front.

    The checks that can be done without writing happen first, so an input that cannot be
    written aborts the run before the first file changes: the text must encode as UTF-8
    (a lone surrogate would not), and an existing file must have its owner write bit
    (st_mode, not os.access: root passes os.access on a 0444 file; a read-only file is a
    deliberate choice the emitter must not replace). I/O failures during the writes are
    one-line errors that say which files, if any, were already written."""
    for path, text in items:
        try:
            text.encode("utf-8")
        except UnicodeError as exc:
            die(f"{path}: cannot encode the new content as UTF-8 ({exc}); nothing was written")
        if path.exists() and not path.stat().st_mode & 0o200:
            die(f"{path}: is read-only (no owner write bit); make it writable or remove it; nothing was written")
    done: list[Path] = []
    for path, text in items:
        try:
            atomic_write(path, text)
        except (OSError, UnicodeError) as exc:
            where = f"already written: {', '.join(map(str, done))}" if done else "nothing was written"
            die(f"{path}: cannot write ({exc}); {where}")
        done.append(path)


def hook_id(command: str) -> str:
    m = OWNED_RE.match(command)
    return m.group(1) if m else command


def describe(current: dict, desired: list[tuple], rel: Path, sweeps=None) -> list[str]:
    """One line per drifting hook id for a settings file: missing, stale (timeout), or
    to be removed. Empty when the owned handlers already match `desired`. `sweeps` is the
    scope predicate merge_owned takes: the other scope's handlers are not drift."""
    have = {(e, m, h["command"]): (h.get("timeout"), h.get("onFailure")) for e, m, h in iter_owned(current)
            if sweeps is None or sweeps(hook_id(h["command"]))}
    want = {(e, m, c): (t, o) for e, m, c, t, o in desired}
    lines = []
    for key in sorted(want, key=lambda k: (k[0], str(k[1]), k[2])):
        if key not in have:
            lines.append(f"missing    {hook_id(key[2])}  ({rel})")
        elif have[key][0] != want[key][0]:
            lines.append(f"stale      {hook_id(key[2])}  ({rel}: timeout {have[key][0]} -> {want[key][0]})")
        elif have[key][1] != want[key][1]:
            lines.append(f"stale      {hook_id(key[2])}  ({rel}: onFailure {have[key][1]} -> {want[key][1]})")
    for key in sorted(set(have) - set(want), key=lambda k: (k[0], str(k[1]), k[2])):
        lines.append(f"remove     {hook_id(key[2])}  ({rel})")
    return lines


# ── user mode ─────────────────────────────────────────────────────────────────
def run_user(args, catalogue: list[dict]) -> None:
    """--user: make the user-level settings file hold exactly the named user-scope hooks
    (and none of the other generated ones). Same merge, safety and no-op rules as project
    mode; the file is created only when an entry has to be added to it."""
    ids = [x.strip() for x in args.hooks.split(",") if x.strip()]
    grid = Path(os.path.abspath(grid_dir()))
    desired = user_desired(catalogue, ids, grid)   # exits 2 on a bad id, before any I/O

    settings = user_settings_path()
    check_user_no_symlinks(settings)
    original, text = read_settings(settings)
    sweeps = sweep_scope(catalogue, "user")   # never sweep the project-scope guards
    try:
        merged = merge_owned(original, desired, sweeps)
    except SettingsError as exc:
        die(f"{settings}: {exc}; nothing was written")

    problems = describe(original, desired, settings, sweeps)
    if merged != original and not problems:
        problems = [f"differs    {settings}  (duplicate generated entries)"]

    names = ", ".join(sorted(hook_id(c) for _e, _m, c, _t, _o in desired)) or "none"
    if args.check:
        if problems:
            print(f"deploy_hooks --check: {settings} differs from the requested user hooks ({names}):", file=sys.stderr)
            for line in problems:
                print(f"  {line}", file=sys.stderr)
            print("  fix: re-run wire.sh (or deploy_hooks.py --user without --check)", file=sys.stderr)
            sys.exit(1)
        print(f"deploy_hooks --check: {settings} matches the requested user hooks ({names}).")
        return
    if args.dry_run:
        print(f"[dry-run] {settings}  user hooks: {names}")
        for line in problems or ["no change"]:
            print(f"  {line}")
        return

    written = 0
    if merged != original:
        new_text = render(merged)
        if new_text != text:  # same bytes: leave the file (and its mtime) alone
            write_files([(settings, new_text)])
            written = 1
    print(f"deploy_hooks: {settings}  user hooks: {names}  {written} written.")


# ── main ──────────────────────────────────────────────────────────────────────
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("project", nargs="?", type=Path, help="target project directory")
    ap.add_argument("--profile", choices=PROFILES, help="override hooks.profile from project.yaml")
    ap.add_argument("--target", choices=TARGETS, help="override hooks.target (local = settings.local.json)")
    ap.add_argument("--check", action="store_true", help="report drift; write nothing; exit 1 on drift")
    ap.add_argument("--dry-run", action="store_true", help="show what would change; write nothing")
    ap.add_argument("--list", action="store_true", help="list every hook with scope, profile and cost, then exit")
    ap.add_argument("--user", action="store_true",
                    help="machine-level mode: write user-scope hooks into ${CLAUDE_CONFIG_DIR:-$HOME/.claude}/settings.json")
    ap.add_argument("--hooks", help='with --user: comma-separated user-scope hook ids that should be present ("" = none)')
    args = ap.parse_args()

    # --user and --hooks go together, and neither mixes with the project-mode inputs.
    if args.user != (args.hooks is not None):
        ap.error("--user and --hooks must be given together")
    if args.user and (args.project is not None or args.profile or args.target or args.list):
        ap.error("--user takes no project directory, --profile, --target or --list")

    catalogue = load_catalogue(grid_dir())
    if args.list:
        print_list(catalogue)
        return
    if args.user:
        run_user(args, catalogue)
        return
    if args.project is None:
        ap.error("project directory is required (or use --list)")
    project = args.project.expanduser().resolve()
    if not project.is_dir():
        die(f"{project} is not a directory")
    check_no_symlinks(project)

    cfg = load_hooks_config(project)
    profile = args.profile or cfg.get("profile") or "off"      # flag, file, then off
    target = args.target or cfg.get("target") or "local"        # flag, file, then local
    learning = load_learning_flag(project)
    desired = desired_for(catalogue, profile, learning)
    # True when this run emits the instincts (opt_in: learning) hooks.
    emitting_learning = learning and any(
        h.get("opt_in") == "learning" and h["scope"] == "project" for h in catalogue)

    # --- plan every file before touching any: both settings files are swept; only the
    # target gets additions, so a target change moves entries instead of duplicating them.
    plan = []  # (rel path, original dict, original text, merged dict, desired for this file)
    sweeps = sweep_scope(catalogue, "project")  # never sweep a user-scope handler sharing the file
    for name, rel in SETTINGS_REL.items():
        want = desired if name == target else []
        original, text = read_settings(project / rel)
        try:
            merged = merge_owned(original, want, sweeps)
        except SettingsError as exc:
            die(f"{project / rel}: {exc}; nothing was written")
        plan.append((rel, original, text, merged, want))

    # --- drift lines (used by --check and --dry-run) ---------------------------------
    problems = []
    for rel, original, _text, merged, want in plan:
        lines = describe(original, want, rel, sweeps)
        if merged != original and not lines:
            lines = [f"differs    {rel}  (duplicate generated entries)"]
        problems += lines

    if args.check:
        if problems:
            print(f"deploy_hooks --check: {project} differs from profile {profile}:", file=sys.stderr)
            for line in problems:
                print(f"  {line}", file=sys.stderr)
            print("  fix: re-run deploy_hooks.py without --check", file=sys.stderr)
            sys.exit(1)
        print(f"deploy_hooks --check: {project} matches the catalogue ({len(desired)} hook(s), profile {profile}).")
        return

    if args.dry_run:
        print(f"[dry-run] {project}  profile={profile}  target={target}")
        for line in problems or ["no change"]:
            print(f"  {line}")
        return

    # --- apply -------------------------------------------------------------------
    todo = []
    for rel, original, text, merged, _want in plan:
        if merged == original:
            continue  # nothing to do; also covers "do not create a file just to leave it empty"
        new_text = render(merged)
        if new_text == text:
            continue  # same bytes: leave the file (and its mtime) alone
        todo.append((project / rel, new_text))
    write_files(todo)  # checks every file before the first write
    changed = len(todo)
    print(f"deploy_hooks: {project}  profile={profile}  target={target}  {len(desired)} hook(s), {changed} written.")
    # Marker work only on a real apply (skipped under --check and --dry-run above).
    sync_learning_marker(project, emitting_learning)
    if emitting_learning:
        print(NOTICE)


if __name__ == "__main__":
    main()
